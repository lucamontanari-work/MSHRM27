// Reads brand/svg/*.svg and writes components/brand/paths.ts.
// Keeps the SVGs as the single source: rerun `npm run brand` when new exports arrive.
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join, basename } from "node:path";

const dir = "brand/svg";
const out = {};

for (const file of readdirSync(dir).filter((f) => f.endsWith(".svg"))) {
  const svg = readFileSync(join(dir, file), "utf8");
  const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
  const shapes = [];
  const eyelets = {};
  for (const m of svg.matchAll(/<path id="([^"]+)"[^>]*\sd="([^"]+)"/g)) {
    const [, id, d] = m;
    if (id === "eyelet-left") eyelets.left = d;
    else if (id === "eyelet-right") eyelets.right = d;
    else shapes.push(d);
  }
  const key = basename(file, ".svg").replace(/^mshrm-/, "");
  out[key] = { viewBox, shapes, ...(eyelets.left ? { eyelets } : {}) };
}

const body = Object.entries(out)
  .map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`)
  .join("\n");

writeFileSync(
  "components/brand/paths.ts",
  `// Generated by scripts/svg-to-ts.mjs from brand/svg. Do not edit by hand.\n\nexport type BrandShape = {\n  viewBox: string;\n  shapes: string[];\n  eyelets?: { left: string; right: string };\n};\n\nexport const brand = {\n${body}\n} satisfies Record<string, BrandShape>;\n`,
);
console.log("brand paths:", Object.keys(out).join(", "));
